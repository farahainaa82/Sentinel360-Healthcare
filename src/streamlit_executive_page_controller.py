def _warning_severity_score(warning_level: str) -> float:
    """Severity score from warning level for primary KPI ranking."""
    w = str(warning_level or "").strip().lower()
    if "high early" in w:
        return 5.0
    if "escalating" in w:
        return 4.0
    if "emerging" in w:
        return 3.0
    if "monitoring" in w:
        return 1.0
    return 0.0


def _split_primary_and_supporting(all_cards):
    """Split six KPI cards into primary (3 highest severity) and supporting (3 remaining).

    Preserves operational order in the supporting row.
    """
    if not all_cards:
        return [], []

    # KPI operational order for tie-breaking and supporting row
    kpi_order = ["kpi_001", "kpi_002", "kpi_003", "kpi_004", "kpi_005", "kpi_006"]

    # Sort by severity descending, then by operational order ascending
    def _sort_key(card):
        kpi_id = card.get("kpi_id", "")
        severity = card.get("severity_score", 0)
        order_index = kpi_order.index(kpi_id) if kpi_id in kpi_order else 99
        return (-severity, order_index)

    sorted_cards = sorted(all_cards, key=_sort_key)
    primary = sorted_cards[:3]
    supporting = sorted(sorted_cards[3:], key=lambda c: kpi_order.index(c.get("kpi_id", "")) if c.get("kpi_id", "") in kpi_order else 99)
    return primary, supporting



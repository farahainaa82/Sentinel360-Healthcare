def _build_scenario_comparison_block(
    scenarios, packages, selected_date, kpi_dept
):
    """Build a structured scenario comparison block with scenario-specific financial linkage.

    Returns a dict with:
      - has_quantified (bool)
      - scenarios (list[dict]) — up to 3 valid scenarios
      - explanation (str) — fallback text when no valid scenarios
      - next_step (str)
    """
    result = {
        "has_quantified": False,
        "scenarios": [],
        "explanation": "",
        "next_step": "",
    }

    if scenarios is None or scenarios.empty:
        result["explanation"] = (
            "Scenario comparison requires scenario-specific financial linkage.\n"
            "Next step: link each scenario to its financial estimate using scenario_id and decision_package_id."
        )
        result["next_step"] = "link each scenario to its financial estimate using scenario_id and decision_package_id"
        return result

    valid_scenarios = []
    scenario_fields = [
        ("Baseline", "baseline_summary"),
        ("Conservative", "conservative_summary"),
        ("Expected", "expected_summary"),
        ("Higher Intensity", "higher_intensity_summary"),
    ]

    for _, row in scenarios.iterrows():
        confidence = row.get("confidence", "")
        for label, col in scenario_fields:
            summary = row.get(col)
            if summary and str(summary).strip():
                # Look up scenario-specific financial fields
                cost = row.get("scenario_cost")
                benefit = row.get("scenario_benefit")
                net = row.get("scenario_net_impact")
                # Fallback to prefixed columns if available
                if cost is None or pd.isna(cost):
                    cost = row.get(f"{col.replace('_summary', '')}_cost")
                if benefit is None or pd.isna(benefit):
                    benefit = row.get(f"{col.replace('_summary', '')}_benefit")
                if net is None or pd.isna(net):
                    net = row.get(f"{col.replace('_summary', '')}_net")
                # Never expose nan
                if cost is not None and pd.isna(cost):
                    cost = None
                if benefit is not None and pd.isna(benefit):
                    benefit = None
                if net is not None and pd.isna(net):
                    net = None
                # If no scenario-specific financials at all, mark incomplete
                has_scenario_financials = any(v is not None for v in [cost, benefit, net])
                if not has_scenario_financials:
                    # Do not fabricate — this scenario lacks linkage
                    continue
                valid_scenarios.append({
                    "label": label,
                    "summary": str(summary).strip(),
                    "cost": cost,
                    "benefit": benefit,
                    "net": net,
                    "confidence": str(confidence).strip() if confidence else "",
                })

    # De-duplicate by label and cap at 3
    seen = set()
    deduped = []
    for s in valid_scenarios:
        if s["label"] not in seen:
            seen.add(s["label"])
            deduped.append(s)
    valid_scenarios = deduped[:3]

    if valid_scenarios:
        result["has_quantified"] = True
        result["scenarios"] = valid_scenarios
        result["explanation"] = ""
        result["next_step"] = ""
    else:
        result["explanation"] = (
            "Scenario comparison requires scenario-specific financial linkage.\n"
            "No quantified scenario financials were found for the selected package."
        )
        result["next_step"] = "link each scenario to its financial estimate using scenario_id and decision_package_id"

    return result



def _compact_currency(value):
    """Compact currency for financial display (RM prefix)."""
    if value is None or pd.isna(value):
        return "Not Available"
    try:
        v = float(value)
        if abs(v) >= 1e6:
            return f"RM{v/1e6:,.2f}M"
        elif abs(v) >= 1e3:
            return f"RM{v/1e3:,.1f}K"
        else:
            return f"RM{v:,.0f}"
    except Exception:
        return str(value)



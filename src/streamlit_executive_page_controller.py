def _forecast_interpretation_fallback(card: dict) -> tuple:
    """Return deterministic (what, why) text for a forecast KPI.

    Mirrors the fallback logic in ``AIKPIGraphSynthesisService``
    so the UI is consistent whether the service is called inline
    or passed from the page layer.
    """
    period_type = card.get("period_type", "FORECAST")
    month = card.get("month")  # not stored in card; use selected context externally
    # Derive a month name from the card's annual_df if available
    annual_df = card.get("annual_df")
    forecast_month = "the forecast period"
    if annual_df is not None and not annual_df.empty:
        fc_rows = annual_df[annual_df.get("source_type", "") == "FORECAST"] if "source_type" in annual_df.columns else annual_df.iloc[-1:]
        if not fc_rows.empty:
            m = fc_rows.iloc[-1].get("month")
            if m is not None:
                month_names = [
                    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
                    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
                ]
                forecast_month = month_names[int(m) - 1]

    warning = str(card.get("warning_level", "Monitoring") or "Monitoring").strip()
    change = str(card.get("expected_status_change", "") or "").strip()

    if change:
        what = (
            f"The {forecast_month} forecast indicates performance "
            f"is expected to move from {change}."
        )
    else:
        what = (
            f"The {forecast_month} forecast indicates the current "
            f"trajectory is unchanged."
        )

    if warning and warning != "Monitoring":
        why = (
            f"A {warning} has been identified and warrants "
            f"continued management monitoring."
        )
    else:
        why = (
            "Current performance is within expected parameters and "
            "should continue to be monitored."
        )

    return what, why


def _map_quality_to_confidence_label(quality: str) -> str:
    """Map forecast quality label to a confidence label."""
    q = str(quality or "").strip().lower()
    if "high" in q:
        return "High Confidence"
    if "low" in q:
        return "Low Confidence"
    return "Moderate Confidence"


def _forecast_op_outlook(kpi_id: str, status_label: str, warning_level: str, expected_change: str) -> str:
    """Forward-looking operational outlook text for a forecast KPI."""
    severity = "high" if status_label == "Critical" else ("moderate" if status_label == "Warning" else "low")
    change = str(expected_change or "").lower()
    direction = "deterioration" if any(t in change for t in ("deteriorat", "worsen", "escalat")) else ("stable" if status_label == "Acceptable" else "potential change")
    return (
        f"This KPI is projected to enter a {severity}-severity band under the current trend "
        f"({direction}). The forecast is indicative and may shift as new evidence arrives."
    )


def _fmt(value):
    """Format a numeric value to one decimal place."""
    try:
        return f"{float(value):.1f}"
    except (TypeError, ValueError):
        return str(value)


# Clean unit suffix map for KPI value display.
# Keys are matched case-insensitively against the raw `unit` field from the
# KPI daily data (e.g. "Percent", "Minutes", "Score (1-5 scale)",
# "Complaints per 1000 encounters"). Values are the cleaned user-facing suffix
# appended to the numeric value.
_UNIT_SUFFIX_MAP = {
    "percent": "%",
    "%": "%",
    "minutes": " minutes",
    "score (1-5 scale)": "/5 Likert",
    "score (1-5)": "/5 Likert",
    "1-5 likert score": "/5 Likert",
    "1-5 likert": "/5 Likert",
    "likert": "/5 Likert",
    "complaints per 1000 encounters": " complaints per 1,000 encounters",
    "complaints per 1,000 encounters": " complaints per 1,000 encounters",
}


def format_unit_value(value, unit: str) -> str:
    """Render a KPI value with a clean user-facing unit suffix, e.g. '88.1%'.

    Always returns one decimal place for numeric inputs. Non-numeric inputs
    (e.g. "N/A", "No data", "Forecast Not Available") are returned as-is so
    callers can pass through missing-data markers without double-formatting.
    """
    if value is None:
        return "N/A"
    s = str(value).strip()
    if s == "" or s.lower() in ("n/a", "no data", "nan", "forecast not available", "insufficient data"):
        return s if s else "N/A"
    # Re-format numeric values to one decimal place; preserve pre-formatted strings
    try:
        v = float(s)
        v_str = f"{v:.1f}"
    except (TypeError, ValueError):
        v_str = s

    raw_unit = (unit or "").strip()
    if not raw_unit:
        return v_str
    suffix = _UNIT_SUFFIX_MAP.get(raw_unit.lower(), f" {raw_unit}")
    # Already starts with a space for some suffixes; for "%" and "/5 Likert" do
    # not add a leading space.
    if suffix.startswith(" ") or suffix.startswith("/"):
        return f"{v_str}{suffix}"
    return f"{v_str}{suffix}"



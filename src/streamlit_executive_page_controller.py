    selected_date = filters.get("reporting_date")

    # Extract data from dict with backward-compatible key fallbacks
    kpi_daily = data.get("kpi_daily", pd.DataFrame()) if data else pd.DataFrame()
    risk_alert = data.get("risk_alert", pd.DataFrame()) if data else pd.DataFrame()
    if data:
        financial = data.get("financial_impact", pd.DataFrame())
        if financial.empty:
            financial = data.get("financial", pd.DataFrame())
        integrated_decision = data.get("integrated_decision", pd.DataFrame())
        if integrated_decision.empty:
            integrated_decision = data.get("situations", pd.DataFrame())
        scenarios = data.get("scenario_comparison", pd.DataFrame())
        if scenarios.empty:
            scenarios = data.get("scenarios", pd.DataFrame())
        forecast_df = data.get("forecast_monthly", pd.DataFrame())
        warning_df = data.get("forecast_warnings", pd.DataFrame())
        eligibility_df = data.get("forecast_eligibility", pd.DataFrame())
        method_df = data.get("forecast_method", pd.DataFrame())
    else:
        financial = pd.DataFrame()
        integrated_decision = pd.DataFrame()
        scenarios = pd.DataFrame()
        forecast_df = pd.DataFrame()
        warning_df = pd.DataFrame()
        eligibility_df = pd.DataFrame()
        method_df = pd.DataFrame()

    # Period classification (ACTUAL vs FORECAST)
    period_type = get_period_type(year, month)

    # Load threshold configuration
    threshold_cfg = load_kpi_threshold_config()

    # Build all six KPI cards with value-based status (uses selected month)
    all_kpi_cards = _build_all_kpi_cards(
        kpi_daily, kpi_dept, selected_date, None, None, threshold_cfg,
        hospital_id=hospital_id, year=year, month=month,
        forecast_df=forecast_df,
        warning_df=warning_df,
        eligibility_df=eligibility_df,
    )
    primary_kpi_cards, supporting_kpi_cards = _split_primary_and_supporting(all_kpi_cards)

    # Evaluate all 6 KPIs for dominant issue selection using the same card data
    # This ensures the dominant issue reflects the exact values shown on the cards
    STATUS_TEXT_TO_STATUS = {
        "Critical": "Red",
        "Warning": "Amber",
        "Acceptable": "Green",
        "Monitoring": "Monitoring",
        "Not Assessable": "Monitoring",
        "Insufficient Data": "Monitoring",
    }
    all_kpi_statuses = {}
    for card in all_kpi_cards:
        kpi_id = card.get("kpi_id")
        if not kpi_id:
            continue
        status_text = card.get("threshold_status", "Monitoring")
        raw_status = STATUS_TEXT_TO_STATUS.get(status_text, "Monitoring")
        all_kpi_statuses[kpi_id] = {
            "kpi_id": kpi_id,
            "kpi_name": card.get("kpi_name", ""),
            "status": raw_status,
            "severity_score": card.get("severity_score", 0),
        }

    # Select dominant issue using value-based evaluation (not package inheritance)
    dominant_result = select_dominant_issue(all_kpi_statuses)
    dominant_kpi_id = dominant_result["dominant_kpi_id"]
    dominant_kpi_name = dominant_result["dominant_kpi_name"]
    dominant_status = dominant_result["dominant_status"]

    # Derive operational status from the selected-month KPI cards
    operational_status = _derive_operational_status_from_cards(primary_kpi_cards)
    if operational_status == "PRIORITY MANAGEMENT REVIEW":
        risk_tier = "High"
    elif operational_status == "MANAGEMENT REVIEW REQUIRED":
        risk_tier = "Medium"
    else:
        risk_tier = "Low"

    # Select primary package from risk_alert filtered by selected context
    primary_pkg = None
    risk_alert_for_selection = None
    DEPT_CODE_TO_NAME = {
        "DEPT-ED": "Emergency Department",
        "DEPT-ICU": "Intensive Care Unit",
        "DEPT-MED": "Medical Ward",
        "DEPT-ADM": "Admissions",
        "DEPT-DIAG": "Diagnostics",
        "DEPT-OPC": "Outpatient Clinic",
        "DEPT-SUR": "Surgery",
        "DEPT-PE": "Patient Experience",
    }
    if risk_alert is not None and not risk_alert.empty:
        risk_alert_for_selection = risk_alert.copy()
        # Filter by department (try both code and name columns)
        if kpi_dept != "ALL":
            dept_name = DEPT_CODE_TO_NAME.get(kpi_dept, kpi_dept)
            dept_matches = None
            if "department_id" in risk_alert_for_selection.columns:
                dept_matches = risk_alert_for_selection[risk_alert_for_selection["department_id"] == kpi_dept]
            if (dept_matches is None or dept_matches.empty) and "affected_department" in risk_alert_for_selection.columns:
                dept_matches = risk_alert_for_selection[risk_alert_for_selection["affected_department"] == dept_name]
            if dept_matches is not None and not dept_matches.empty:
                risk_alert_for_selection = dept_matches
            else:
                # No department match found — do not silently fallback; keep empty
                risk_alert_for_selection = risk_alert_for_selection.iloc[0:0]
        # Filter by selected year and month
        if "reporting_date" in risk_alert_for_selection.columns and not risk_alert_for_selection.empty:
            risk_alert_for_selection["ra_year"] = pd.to_datetime(risk_alert_for_selection["reporting_date"], errors="coerce").dt.year
            risk_alert_for_selection["ra_month"] = pd.to_datetime(risk_alert_for_selection["reporting_date"], errors="coerce").dt.month
            risk_alert_for_selection = risk_alert_for_selection[
                (risk_alert_for_selection["ra_year"] == year) &
                (risk_alert_for_selection["ra_month"] == month)
            ]
        if not risk_alert_for_selection.empty:
            primary_pkg = select_primary_package(risk_alert_for_selection)

    pkg_date = None
    if primary_pkg is not None and "reporting_date" in primary_pkg:
        pkg_date = primary_pkg["reporting_date"]

    # Build operational pressure story using primary cards only
    operational_story = _build_operational_pressure_story(
        primary_kpi_cards, primary_pkg, threshold_cfg
    )

    # Management action tailored to the actual dominant KPI
    management_action = _get_kpi_specific_management_action(dominant_kpi_id, dominant_status)
    if not dominant_kpi_id:
        management_action = "No material operational breach. Continue routine monitoring."

    # Forecast context: capability notice + dominant warning + suggested action
    forecast_capability = get_forecast_capability_notice()
    dominant_forecast_warning = {}
    if period_type == "FORECAST" and kpi_dept != "ALL" and dominant_kpi_id:
        dominant_forecast_warning = lookup_forecast_warning(
            warning_df, hospital_id, kpi_dept, dominant_kpi_id, year, month
        )

    # Canonical selected context object
    selected_context = {
        "hospital_id": hospital_id,
        "hospital_name": hospital_id,
        "department_id": kpi_dept,
        "department_name": dept_name,
        "selected_year": year,
        "selected_month": month,
        "selected_period_start": selected_date,
        "selected_period_end": selected_date,
        "period_type": "monthly",
        "relevant_kpi_ids": ["kpi_001", "kpi_002", "kpi_003", "kpi_004", "kpi_005", "kpi_006"],
        "scenario_id": None,
    }

    # Build financial impact block with State A/B logic
    financial_impact_block = _build_financial_impact_block(
        primary_pkg, selected_date, financial, integrated_decision, selected_context
    )
    financial_block_text = financial_impact_block.get("text", "")

    # Narrative that reflects the actual dominant issue (or stable state)
    narrative = _build_executive_narrative_block(
        dept_name, selected_date, dominant_kpi_name, dominant_kpi_id, dominant_status,
        primary_kpi_cards, financial_block_text, selected_date
    )

    financial_narrative = (
        f"Financial impact as of {selected_date}: "
        f"{financial_block_text}."
    )

    scenario_comparison = _build_scenario_comparison_block(
        scenarios, risk_alert, selected_date, kpi_dept
    )
    # Ensure scenario_comparison is a dict (new structured format)
    if isinstance(scenario_comparison, str):
        scenario_comparison = {
            "has_quantified": False,
            "scenarios": [],
            "explanation": scenario_comparison,
            "next_step": "",
        }

    situation_builders = _build_situation_builders()
    situation_kpis = _build_situation_kpis("Informed", kpi_daily, kpi_dept)
    situation_narrative = _build_situation_narrative("Informed", kpi_daily, kpi_dept)

    header = _build_5_piece_header(dept_name, selected_date, primary_pkg, risk_alert)

    # Backward-compatible state mapping for the page
    return {
        "header": header,
        "three_kpi_cards": primary_kpi_cards,
        "primary_kpi_cards": primary_kpi_cards,
        "supporting_kpi_cards": supporting_kpi_cards,
        "all_kpi_cards": all_kpi_cards,
        "all_kpi_statuses": all_kpi_statuses,
        "dominant_kpi_id": dominant_kpi_id,
        "dominant_kpi_name": dominant_kpi_name,
        "dominant_status": dominant_status,
        "operational_status": operational_status,
        "risk_tier": risk_tier,
        "operational_story": operational_story,
        "management_action": management_action,
        "narrative": narrative,
        "financial_block": financial_block_text,
        "financial_impact_block": financial_impact_block,
        "financial_narrative": financial_narrative,
        "scenario_comparison": scenario_comparison,
        "situation_builders": situation_builders,
        "situation_kpis": situation_kpis,
        "situation_narrative": situation_narrative,
        "primary_package": primary_pkg,
        "risk_alert": risk_alert,
        "selected_date": selected_date,
        "department_name": dept_name,
        "department_id": kpi_dept,
        "threshold_config": threshold_cfg,
        "issue_ranking": dominant_result.get("ranking", []),
        # Forecast context (Phase 3B-FI)
        "period_type": period_type,
        "forecast_capability": forecast_capability,
        "dominant_forecast_warning": dominant_forecast_warning,
        "forecast_monthly": forecast_df,
        "forecast_warnings": warning_df,
        "forecast_eligibility": eligibility_df,
        "forecast_method": method_df,
        # Legacy keys for backward compatibility
        "executive_narrative": narrative,
        "pressure_story": operational_story,
        "management_review": {
            "primary_permitted_action": management_action,
            "executive_headline": "Management Review" if dominant_kpi_id else "Routine Monitoring",
            "issue_summary": dominant_kpi_name if dominant_kpi_id else "No issues identified",
            "readiness": "Ready" if dominant_kpi_id else "Routine",
            "outstanding_condition": "None" if not dominant_kpi_id else "Requires attention",
        },
        "financial": {
            "net": financial_impact_block.get("net"),
            "cost": financial_impact_block.get("cost"),
            "benefit": financial_impact_block.get("benefit"),
            "display_confidence": financial_impact_block.get("confidence", "Not Assessable"),
        },
        "scenario_data": scenario_comparison,
        "selected_context": selected_context,
        "supporting_detail": {},
        "urgency": "Low" if not dominant_kpi_id else "High" if dominant_status == "Red" else "Medium",
        "financial_exposure_display": financial_impact_block.get("text", "N/A"),
    }

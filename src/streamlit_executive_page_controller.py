def _build_operational_pressure_story(primary_kpi_cards, primary_pkg, threshold_cfg):
    """
    Build a Connected Operational Situation story using the evaluated
    primary card statuses (not package-level risk inheritance).
    """
    story_blocks = []
    for card in primary_kpi_cards:
        kpi_name = card.get("kpi_name", "")
        status = card.get("threshold_status", "Monitoring")
        value = card.get("latest_value", "")
        units = card.get("unit", "")
        if status in ("Red", "Critical"):
            story_blocks.append(
                f'<li><strong>Red:</strong> {kpi_name} {value} {units} is in a critical state.</li>'
            )
        elif status in ("Amber", "Warning"):
            story_blocks.append(
                f'<li><strong>Amber:</strong> {kpi_name} {value} {units} is at warning level.</li>'
            )
        elif status in ("Green", "Acceptable"):
            story_blocks.append(
                f'<li><strong>Green:</strong> {kpi_name} {value} {units} is stable.</li>'
            )
        else:
            story_blocks.append(
                f'<li><strong>Monitoring:</strong> {kpi_name} {value} {units} is under observation.</li>'
            )

    if not story_blocks:
        return (
            '<div style="padding: 12px; border-radius: 4px; background: #f3f4f6; margin-top: 12px;">'
            '<p style="margin:0; color:#374151;">No material operational breach is identified for the selected department and period. Continue routine monitoring.</p>'
            '</div>'
        )

    story_html = (
        '<div style="padding: 12px; border-radius: 4px; background: #f3f4f6; margin-top: 12px;">'
        '<ul style="margin: 0; padding-left: 18px; color: #374151; font-size: 13px; line-height: 1.5;">'
        + "".join(story_blocks)
        + '</ul></div>'
    )
    return story_html



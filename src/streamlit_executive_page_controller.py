def _build_financial_impact_block(
    primary_pkg,
    selected_date,
    financial_df,
    integrated_decision_df,
    selected_context=None,
):
    """Build financial impact block with State A (quantified) or State B (readiness).

    Returns a dict with:
        display_state: "QUANTIFIED" or "READINESS"
        text: plain text summary
        html: HTML rendering for the UI
        cost, benefit, net: numeric or None
        confidence, completeness: strings
        missing_inputs: list of strings
        next_step: string
        readiness_reasons: list of strings
        scenario_name: string or None
    """
    result = {
        "display_state": "READINESS",
        "text": "Financial estimate not available for the selected period.",
        "html": "",
        "cost": None,
        "benefit": None,
        "net": None,
        "confidence": "Not Assessable",
        "completeness": "Not Available",
        "missing_inputs": [],
        "next_step": "Validate financial assumptions before management comparison.",
        "readiness_reasons": [],
        "scenario_name": None,
    }

    ctx = selected_context or {}
    ctx_hospital = ctx.get("hospital_id", "")
    ctx_dept = ctx.get("department_id", "")
    ctx_year = ctx.get("selected_year")
    ctx_month = ctx.get("selected_month")

    if not primary_pkg or not primary_pkg.get("decision_package_id"):
        result["readiness_reasons"].append("No primary package selected for the selected context.")
        return result

    pkg_id = primary_pkg.get("decision_package_id", "")
    dept_id = primary_pkg.get("affected_department", primary_pkg.get("department_id", ""))

    # Helper to filter by selected context (hospital, department, year, month)
    def _filter_by_context(df, date_col="reporting_date"):
        if df is None or df.empty:
            return df
        matches = df.copy()
        # Filter by department_code
        if ctx_dept and ctx_dept != "ALL" and "department_id" in matches.columns:
            matches = matches[matches["department_id"] == ctx_dept]
        elif ctx_dept and ctx_dept != "ALL" and "affected_department" in matches.columns:
            matches = matches[matches["affected_department"] == ctx_dept]
        # Filter by year/month from date column
        if ctx_year is not None and ctx_month is not None and date_col in matches.columns:
            matches[date_col] = pd.to_datetime(matches[date_col], errors="coerce")
            matches = matches[
                (matches[date_col].dt.year == ctx_year) &
                (matches[date_col].dt.month == ctx_month)
            ]
        return matches

    # Try to find financial record in integrated decision register
    fin_rec = None
    if integrated_decision_df is not None and not integrated_decision_df.empty:
        if "approval_package_id" in integrated_decision_df.columns:
            matches = integrated_decision_df[integrated_decision_df["approval_package_id"] == pkg_id]
            # Apply context filter to matches
            matches = _filter_by_context(matches, "reporting_date")
            if matches.empty and dept_id and "department_id" in integrated_decision_df.columns:
                matches = integrated_decision_df[integrated_decision_df["department_id"] == dept_id]
                matches = _filter_by_context(matches, "reporting_date")
            if not matches.empty:
                fin_rec = matches.iloc[0]

    if fin_rec is None and financial_df is not None and not financial_df.empty:
        if "decision_package_id" in financial_df.columns:
            matches = financial_df[financial_df["decision_package_id"] == pkg_id]
            matches = _filter_by_context(matches, "reporting_date")
            # Only use dept_id fallback if no selected_context is provided,
            # to avoid cross-month/package matches
            if matches.empty and dept_id and not selected_context:
                matches = financial_df[financial_df["decision_package_id"].str.contains(dept_id, na=False)]
                matches = _filter_by_context(matches, "reporting_date")
            if not matches.empty:
                fin_rec = matches.iloc[0]

    if fin_rec is None:
        result["readiness_reasons"].append("No linked financial record found for the selected context.")
        result["missing_inputs"].append("Financial record not found for selected department and month")
        return result

    # Determine if quantified
    net_impact = fin_rec.get("net_financial_impact")
    # Also accept alternative column names used in different datasets
    cost = fin_rec.get("total_scenario_cost") if "total_scenario_cost" in fin_rec else None
    benefit = fin_rec.get("total_estimated_benefit") if "total_estimated_benefit" in fin_rec else None
    # Fallback: try to derive from other columns if direct columns are absent
    if cost is None and "central_estimate" in fin_rec:
        ce = fin_rec.get("central_estimate")
        if ce is not None and not pd.isna(ce):
            cost = ce
    if benefit is None and "upper_estimate" in fin_rec:
        ue = fin_rec.get("upper_estimate")
        if ue is not None and not pd.isna(ue):
            benefit = ue
    cost_completeness = str(fin_rec.get("cost_completeness_status", "")).strip()
    financial_readiness = str(fin_rec.get("financial_readiness", "")).strip()
    financial_confidence = str(fin_rec.get("financial_confidence", "")).strip()
    missing_flag = fin_rec.get("missing_financial_input_flag")
    review_reason = str(fin_rec.get("financial_review_reason", "")).strip()

    has_net = net_impact is not None and not pd.isna(net_impact)
    has_cost = cost is not None and not pd.isna(cost)
    has_benefit = benefit is not None and not pd.isna(benefit)
    is_not_quantified = (
        "not quantified" in cost_completeness.lower()
        or "not quantified" in financial_readiness.lower()
        or "monitoring only" in cost_completeness.lower()
        or "monitoring only" in financial_readiness.lower()
    )

    result["scenario_name"] = fin_rec.get("scenario_name", primary_pkg.get("dominant_kpi_name", ""))
    result["confidence"] = financial_confidence if financial_confidence else "Not Assessable"
    result["completeness"] = cost_completeness if cost_completeness else "Not Available"

    if has_net and not is_not_quantified:
        # State A: Quantified — reconcile net against benefit - cost
        result["display_state"] = "QUANTIFIED"
        result["cost"] = cost
        result["benefit"] = benefit
        result["net"] = net_impact

        # Reconciliation check
        reconciled = True
        reconciliation_note = ""
        if has_cost and has_benefit:
            try:
                computed_net = float(benefit) - float(cost)
                if abs(float(net_impact) - computed_net) > 0.01 * max(abs(computed_net), 1):
                    reconciled = False
                    reconciliation_note = (
                        f"Financial Reconciliation Required: governed net ({_compact_currency(net_impact)}) "
                        f"does not equal benefit ({_compact_currency(benefit)}) minus cost ({_compact_currency(cost)}). "
                        f"Computed net: {_compact_currency(computed_net)}."
                    )
            except Exception:
                reconciled = False
                reconciliation_note = "Financial Reconciliation Required: unable to verify net = benefit - cost."
        result["reconciled"] = reconciled

        if reconciled:
            has_all_three = has_cost and has_benefit
            if has_all_three:
                # Render signed horizontal bar chart when data is complete
                try:
                    fig = render_financial_impact_chart(cost, benefit, net_impact)
                    result["figure"] = fig
                except Exception:
                    result["figure"] = None
                result["html"] = (
                    f'<p style="margin-top:8px;font-size:12px;color:#6b7280;">'
                    f'Financial confidence: {financial_confidence} | Completeness: {cost_completeness}</p>'
                )
            else:
                # Show itemised rows with Not Available for missing values
                def _fin_row(label, value, colour):
                    if value is None or pd.isna(value):
                        return (
                            f'<div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:6px;padding:4px 0;border-bottom:1px solid #f3f4f6;">'
                            f'<span style="font-size:12px;font-weight:600;">{label}</span>'
                            f'<span style="font-size:12px;color:#9ca3af;font-weight:500;">Not Available</span>'
                            f'</div>'
                        )
                    try:
                        v = float(value)
                        bar_width = min(abs(v) / max(abs(float(net_impact)), 1) * 100, 100)
                        bar_html = (
                            f'<div style="background:#eee;border-radius:4px;height:18px;position:relative;margin-top:4px;">'
                            f'  <div style="background:{colour};width:{bar_width:.1f}%;height:18px;border-radius:4px;"></div>'
                            f'  <span style="position:absolute;right:6px;top:1px;color:#374151;font-size:11px;font-weight:500;">{_compact_currency(value)}</span>'
                            f'</div>'
                        )
                    except Exception:
                        bar_html = f'<span style="font-size:12px;color:#9ca3af;font-weight:500;">Not Available</span>'
                    return (
                        f'<div style="margin-bottom:8px;">'
                        f'<div style="font-size:12px;font-weight:600;">{label}</div>'
                        f'{bar_html}'
                        f'</div>'
                    )
                try:
                    net_colour = "#e74c3c" if float(net_impact) < 0 else "#27ae60"
                except Exception:
                    net_colour = "#6b7280"
                result["html"] = (
                    '<div style="margin-top:8px;">'
                    + _fin_row("Estimated Intervention Cost", cost, "#e74c3c")
                    + _fin_row("Estimated Benefit / Avoided Exposure", benefit, "#27ae60")
                    + _fin_row("Estimated Net Financial Impact", net_impact, net_colour)
                    + '</div>'
                    f'<p style="margin-top:8px;font-size:12px;color:#6b7280;">Financial confidence: {financial_confidence} | Completeness: {cost_completeness}</p>'
                )
            result["text"] = (
                f"Net financial impact: {_compact_currency(net_impact)} "
                f"(Cost: {_compact_currency(cost)}, Benefit: {_compact_currency(benefit)})"
            )
        else:
            # Suppress net bar; show reconciliation warning with available cost/benefit inputs
            result["figure"] = None
            def _fin_row_plain(label, value):
                if value is None or pd.isna(value):
                    return f'<li>{label}: <span style="color:#9ca3af;">Not Available</span></li>'
                return f'<li>{label}: <strong>{_compact_currency(value)}</strong></li>'

            warn_html = (
                '<div style="padding:12px;border-radius:6px;background:#fff3cd;border-left:4px solid #f59e0b;margin-top:8px;">'
                f'<p style="margin:0 0 6px 0;font-weight:600;color:#856404;">⚠️ Financial Reconciliation Required</p>'
                f'<p style="margin:0 0 6px 0;font-size:12px;color:#856404;">{reconciliation_note}</p>'
                '<ul style="margin:0 0 6px 0;padding-left:18px;font-size:12px;">'
                + _fin_row_plain("Estimated Intervention Cost", cost)
                + _fin_row_plain("Estimated Benefit / Avoided Exposure", benefit)
                + _fin_row_plain("Estimated Net Financial Impact", net_impact)
                + '</ul>'
                f'<p style="margin:0;font-size:11px;color:#6b7280;">Financial confidence: {financial_confidence} | Completeness: {cost_completeness}</p>'
                '</div>'
            )
            result["html"] = warn_html
            result["text"] = reconciliation_note
    else:
        # State B: Readiness
        result["display_state"] = "READINESS"
        reasons = []
        if not has_net:
            reasons.append("Net financial impact not quantified.")
        if not has_cost:
            reasons.append("Intervention cost not available.")
        if not has_benefit:
            reasons.append("Estimated benefit not available.")
        if is_not_quantified:
            reasons.append(f"Package status: {cost_completeness or financial_readiness}")
        if missing_flag and str(missing_flag).lower() in ("true", "1", "yes"):
            reasons.append("Missing financial inputs flagged.")
        if review_reason:
            reasons.append(f"Review reason: {review_reason}")
        result["readiness_reasons"] = reasons
        result["missing_inputs"] = reasons

        readiness_html = (
            '<div style="padding:12px;border-radius:6px;background:#f9fafb;border-left:4px solid #f59e0b;">'
            '<p style="margin:0 0 6px 0;font-weight:600;">Estimated impact: Not Yet Quantified</p>'
            f'<p style="margin:0 0 6px 0;">Financial readiness: {financial_readiness or "Requires Intervention Scenario"}</p>'
            '<p style="margin:0 0 4px 0;font-weight:500;">Missing inputs:</p>'
            '<ul style="margin:0;padding-left:18px;font-size:12px;">'
            + "".join(f"<li>{r}</li>" for r in reasons)
            + '</ul>'
            '<p style="margin:8px 0 0 0;font-size:12px;color:#6b7280;">Next required step: Validate financial assumptions before management comparison.</p>'
            '</div>'
        )
        result["html"] = readiness_html
        result["text"] = "Financial impact not yet quantified. " + " ".join(reasons)

    return result



def _card_border_colour(status):
    """Shared status-to-colour mapping."""
    s = str(status).lower()
    if s in ("green", "acceptable", "stable"):
        return "green"
    if s in ("amber", "warning", "watch"):
        return "amber"
    if s in ("red", "critical"):
        return "red"
    if s in ("monitoring", "informational"):
        return "blue"
    return "grey"


def _derive_operational_status_from_cards(cards):
    """Derive operational status from primary KPI cards using selected-month values."""
    if not cards:
        return "MONITORING"
    has_critical = any(c.get("severity_score", 0) >= 3.0 for c in cards)
    has_warning = any(c.get("severity_score", 0) >= 2.0 for c in cards)
    if has_critical:
        return "PRIORITY MANAGEMENT REVIEW"
    if has_warning:
        return "MANAGEMENT REVIEW REQUIRED"
    return "STABLE OPERATIONS"



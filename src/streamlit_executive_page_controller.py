def select_dominant_issue(kpi_statuses, kpi_trends=None):
    """
    Select dominant issue from evaluated KPI statuses.

    kpi_statuses: dict of kpi_id -> evaluate_kpi_status result dict
    kpi_trends: optional dict of kpi_id -> trend score (e.g. recent slope)

    Returns dict with:
        dominant_kpi_id: str or None
        dominant_kpi_name: str or None
        dominant_status: str or None
        ranking: list of dicts sorted by priority
    """
    if not kpi_statuses:
        return {"dominant_kpi_id": None, "dominant_kpi_name": None, "dominant_status": None, "ranking": []}

    kpi_names = {
        "kpi_001": "Staffing Level",
        "kpi_002": "Staff Absenteeism Rate",
        "kpi_003": "Bed Occupancy Rate",
        "kpi_004": "Average Patient Waiting Time",
        "kpi_005": "Patient Complaint Rate",
        "kpi_006": "Patient Satisfaction Score",
    }

    rows = []
    for kpi_id, status_info in kpi_statuses.items():
        severity = status_info.get("severity_score", 0)
        breach = status_info.get("breach_magnitude", 0)
        trend = kpi_trends.get(kpi_id, 0) if kpi_trends else 0

        # Only amber/red KPIs can be dominant; severity >= 2
        if severity < 2:
            continue

        # Composite score: severity (3x) + breach magnitude (1x) + trend (0.5x)
        composite = (severity * 3.0) + (breach * 1.0) + (abs(trend) * 0.5)

        rows.append({
            "kpi_id": kpi_id,
            "kpi_name": kpi_names.get(kpi_id, kpi_id),
            "severity_score": severity,
            "breach_magnitude": breach,
            "trend_score": trend,
            "composite_score": composite,
            "status": status_info.get("status", "Monitoring"),
        })

    if not rows:
        return {"dominant_kpi_id": None, "dominant_kpi_name": None, "dominant_status": None, "ranking": []}

    rows.sort(key=lambda x: x["composite_score"], reverse=True)
    top = rows[0]
    return {
        "dominant_kpi_id": top["kpi_id"],
        "dominant_kpi_name": top["kpi_name"],
        "dominant_status": top["status"],
        "ranking": rows,
    }



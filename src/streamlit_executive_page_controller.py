def load_kpi_threshold_config():
    """Load KPI thresholds from authoritative config with dual-sided boundaries."""
    path = os.path.join("config", "kpi_threshold_config.csv")
    if not os.path.isfile(path):
        return {}
    try:
        df = pd.read_csv(path)
        config = {}
        for _, row in df.iterrows():
            kpi_id = str(row.get("kpi_id", "")).strip()
            if not kpi_id:
                continue
            directionality_raw = str(row.get("directionality", "")).strip().lower()
            if directionality_raw == "higher is better":
                directionality = "HIGHER_IS_BETTER"
            elif directionality_raw == "lower is better":
                directionality = "LOWER_IS_BETTER"
            elif directionality_raw == "context-sensitive":
                directionality = "TARGET_BAND"
            else:
                directionality = _correct_directionality(kpi_id, directionality_raw)

            def _f(val):
                if pd.isna(val) or val == "" or val == "nan":
                    return None
                try:
                    return float(val)
                except Exception:
                    return None

            config[kpi_id] = {
                "kpi_name": str(row.get("kpi_name", "")),
                "directionality": directionality,
                "lower_red_boundary": _f(row.get("lower_red_boundary")),
                "lower_amber_boundary": _f(row.get("lower_amber_boundary")),
                "green_lower_boundary": _f(row.get("green_lower_boundary")),
                "green_upper_boundary": _f(row.get("green_upper_boundary")),
                "upper_amber_boundary": _f(row.get("upper_amber_boundary")),
                "upper_red_boundary": _f(row.get("upper_red_boundary")),
                "unit": str(row.get("unit", "")),
                "approval_status": str(row.get("approval_status", "Provisional")),
                "effective_date": str(row.get("effective_date", "")),
                "threshold_is_provisional": bool(row.get("threshold_is_provisional", False)),
                "conditions_of_approval": str(row.get("conditions_of_approval", "")) if not pd.isna(row.get("conditions_of_approval")) else "",
            }
        return config
    except Exception as e:
        if _log:
            _log.warning(f"Threshold config load failed: {e}")
        return {}


def _correct_directionality(kpi_id, raw):
    """Return the clinically correct directionality regardless of config label errors."""
    mapping = {
        "kpi_001": "HIGHER_IS_BETTER",
        "kpi_002": "LOWER_IS_BETTER",
        "kpi_003": "TARGET_BAND",
        "kpi_004": "LOWER_IS_BETTER",
        "kpi_005": "LOWER_IS_BETTER",
        "kpi_006": "HIGHER_IS_BETTER",
    }
    return mapping.get(kpi_id, raw.upper() if raw else "LOWER_IS_BETTER")


def normalize_kpi_value_and_thresholds(value, thresholds, unit=None):
    """
    Normalize KPI value and thresholds to a canonical scale.

    Canonical percentage scale: 0-100 (percentage points).
    A value of 84.6 represents 84.6 percent.
    A threshold of 15.0012 represents 15.0012 percent.

    If the unit is 'Percent' and a scale mismatch is detected between
    value and thresholds (e.g., value=0.154 vs threshold=15.4),
    the value is scaled to percentage points.

    Returns:
        dict with keys:
            value: normalized value
            thresholds: dict of normalized threshold values
            canonical_scale: "0-100" for Percent, otherwise "raw"
            scale_adjusted: bool indicating whether scaling was applied
    """
    normalized_value = value
    normalized_thresholds = dict(thresholds) if thresholds else {}
    scale_adjusted = False
    canonical_scale = "raw"

    if unit and "percent" in str(unit).lower():
        canonical_scale = "0-100"

        # Detect if value is in fraction scale (0-1) while thresholds are in percentage points (0-100)
        if value is not None and isinstance(value, (int, float)):
            thr_values = [
                v
                for v in normalized_thresholds.values()
                if v is not None and isinstance(v, (int, float))
            ]
            if thr_values:
                value_is_fraction = 0 < abs(value) < 1
                thresholds_are_points = all(abs(v) >= 1 for v in thr_values)
                if value_is_fraction and thresholds_are_points:
                    normalized_value = value * 100
                    scale_adjusted = True
                elif not value_is_fraction and all(0 < abs(v) < 1 for v in thr_values):
                    for k, v in normalized_thresholds.items():
                        if v is not None and isinstance(v, (int, float)) and 0 < abs(v) < 1:
                            normalized_thresholds[k] = v * 100
                    scale_adjusted = True

    return {
        "value": normalized_value,
        "thresholds": normalized_thresholds,
        "canonical_scale": canonical_scale,
        "scale_adjusted": scale_adjusted,
    }


def evaluate_kpi_status(
    kpi_id,
    value,
    lower_red_boundary=None,
    lower_amber_boundary=None,
    green_lower_boundary=None,
    green_upper_boundary=None,
    upper_amber_boundary=None,
    upper_red_boundary=None,
    directionality=None,
    unit=None,
    approval_status=None,
    effective_date=None,
):
    """
    Authoritative KPI status evaluation using dual-sided boundary thresholds.

    Returns dict with:
        status: one of "Green", "Amber", "Red", "Monitoring", "Not Assessable"
        status_text: "Acceptable", "Warning", "Critical", "Monitoring", "Not Assessable"
        border_colour: "green", "amber", "red", "blue", "grey"
        severity_score: float for ranking (Red=3, Amber=2, Green=1, Monitoring=0, Not Assessable=0)
        breach_magnitude: float (0 if Green/Monitoring/Not Assessable)
        status_meta: str explaining the rule source used
    """
    result = {
        "status": "Monitoring",
        "status_text": "Monitoring",
        "border_colour": "blue",
        "severity_score": 0.0,
        "breach_magnitude": 0.0,
        "status_meta": "Status cannot be determined",
    }

    if not isinstance(value, (int, float)) or pd.isna(value):
        return result

    # Normalize value and thresholds to canonical scale
    thresholds = {
        "lower_red": lower_red_boundary,
        "lower_amber": lower_amber_boundary,
        "green_lower": green_lower_boundary,
        "green_upper": green_upper_boundary,
        "upper_amber": upper_amber_boundary,
        "upper_red": upper_red_boundary,
    }
    normalized = normalize_kpi_value_and_thresholds(value, thresholds, unit)
    value = normalized["value"]
    t = normalized["thresholds"]

    def _to_float(x):
        if x is None or (isinstance(x, str) and str(x).strip() == ""):
            return None
        try:
            return float(x)
        except (ValueError, TypeError):
            return None

    lower_red = _to_float(t.get("lower_red"))
    lower_amber = _to_float(t.get("lower_amber"))
    green_lower = _to_float(t.get("green_lower"))
    green_upper = _to_float(t.get("green_upper"))
    upper_amber = _to_float(t.get("upper_amber"))
    upper_red = _to_float(t.get("upper_red"))

    # Missing or invalid threshold configuration must not default silently to Green
    all_thresholds = [lower_red, lower_amber, green_lower, green_upper, upper_amber, upper_red]
    if all(v is None for v in all_thresholds):
        result["status"] = "Not Assessable"
        result["status_text"] = "Not Assessable"
        result["border_colour"] = "grey"
        result["severity_score"] = 0.0
        result["status_meta"] = "Threshold Configuration Required"
        return result

    direction = (directionality or "LOWER_IS_BETTER").upper()

    # Identify provisional thresholds in status_meta
    provisional = ""
    if approval_status and str(approval_status).lower() in ("draft", "provisional"):
        provisional = f" [Provisional threshold, effective {effective_date}]"

    def _dist_to_boundary(val, boundary):
        if boundary is None or boundary == 0:
            return abs(val - boundary) if boundary is not None else 0
        return abs(val - boundary) / abs(boundary)

    if direction == "HIGHER_IS_BETTER":
        # Higher values are better.
        # Red: value <= lower_red (critically low)
        # Amber: lower_red < value < lower_amber (below warning)
        # Green: value >= green_lower (acceptable)
        green_bound = green_lower if green_lower is not None else (lower_amber if lower_amber is not None else None)
        amber_bound = lower_amber if lower_amber is not None else green_bound
        red_bound = lower_red

        if red_bound is not None and value <= red_bound:
            result["status"] = "Red"
            result["status_text"] = "Critical"
            result["border_colour"] = "red"
            result["severity_score"] = 3.0
            result["breach_magnitude"] = _dist_to_boundary(value, red_bound)
            result["status_meta"] = f"Below critical threshold ({red_bound}){provisional}"
        elif amber_bound is not None and value < amber_bound:
            result["status"] = "Amber"
            result["status_text"] = "Warning"
            result["border_colour"] = "amber"
            result["severity_score"] = 2.0
            result["breach_magnitude"] = _dist_to_boundary(value, amber_bound)
            result["status_meta"] = f"Below warning threshold ({amber_bound}){provisional}"
        elif green_bound is not None and value >= green_bound:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"Above green threshold ({green_bound}){provisional}"
        elif green_upper is not None and value <= green_upper:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"Within green upper bound ({green_upper}){provisional}"
        else:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"No threshold exceeded{provisional}"

    elif direction == "LOWER_IS_BETTER":
        # Lower values are better.
        # Red: value >= upper_red (critically high)
        # Amber: value > green_upper (above green band, below critical)
        # Green: value <= green_upper (acceptable)
        green_bound = green_upper if green_upper is not None else (upper_amber if upper_amber is not None else None)
        red_bound = upper_red

        if red_bound is not None and value >= red_bound:
            result["status"] = "Red"
            result["status_text"] = "Critical"
            result["border_colour"] = "red"
            result["severity_score"] = 3.0
            result["breach_magnitude"] = _dist_to_boundary(value, red_bound)
            result["status_meta"] = f"Above critical threshold ({red_bound}){provisional}"
        elif green_bound is not None and value > green_bound:
            result["status"] = "Amber"
            result["status_text"] = "Warning"
            result["border_colour"] = "amber"
            result["severity_score"] = 2.0
            result["breach_magnitude"] = _dist_to_boundary(value, green_bound)
            result["status_meta"] = f"Above warning threshold ({green_bound}){provisional}"
        elif green_bound is not None and value <= green_bound:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"Below green threshold ({green_bound}){provisional}"
        elif green_lower is not None and value >= green_lower:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"Above green lower bound ({green_lower}){provisional}"
        else:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"No threshold exceeded{provisional}"

    elif direction == "TARGET_BAND":
        # Target band: values inside green_lower..green_upper are Green.
        # Values outside the band but within red boundaries are Amber.
        # Values beyond red boundaries are Red.
        if lower_red is not None and value <= lower_red:
            result["status"] = "Red"
            result["status_text"] = "Critical"
            result["border_colour"] = "red"
            result["severity_score"] = 3.0
            result["breach_magnitude"] = _dist_to_boundary(value, lower_red)
            result["status_meta"] = f"Below critical lower bound ({lower_red}){provisional}"
        elif upper_red is not None and value >= upper_red:
            result["status"] = "Red"
            result["status_text"] = "Critical"
            result["border_colour"] = "red"
            result["severity_score"] = 3.0
            result["breach_magnitude"] = _dist_to_boundary(value, upper_red)
            result["status_meta"] = f"Above critical upper bound ({upper_red}){provisional}"
        elif green_lower is not None and value < green_lower:
            result["status"] = "Amber"
            result["status_text"] = "Warning"
            result["border_colour"] = "amber"
            result["severity_score"] = 2.0
            result["breach_magnitude"] = _dist_to_boundary(value, green_lower)
            result["status_meta"] = f"Below green lower bound ({green_lower}){provisional}"
        elif green_upper is not None and value > green_upper:
            result["status"] = "Amber"
            result["status_text"] = "Warning"
            result["border_colour"] = "amber"
            result["severity_score"] = 2.0
            result["breach_magnitude"] = _dist_to_boundary(value, green_upper)
            result["status_meta"] = f"Above green upper bound ({green_upper}){provisional}"
        else:
            result["status"] = "Green"
            result["status_text"] = "Acceptable"
            result["border_colour"] = "green"
            result["severity_score"] = 1.0
            result["status_meta"] = f"Within target band{provisional}"

    else:
        result["status"] = "Monitoring"
        result["status_text"] = "Monitoring"
        result["border_colour"] = "blue"
        result["severity_score"] = 0.0
        result["status_meta"] = "Unknown directionality"

    return result


